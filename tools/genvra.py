#!/usr/bin/env python3
"""Generate src/MKBibVrA.pas, the Apocrypha of the KJVA and NRSVA versifications, from Sword's canon*.h files.
Usage: genvra.py <sword include dir> <out.pas>

Why these come from Sword: a Sword module's index files are laid out by Sword's own tables, so reading one
needs exactly Sword's chapter and verse counts for the Apocrypha, which differ from the real books in places
(Prayer of Manasseh is one verse, the Additions to Esther are 16 chapters, ...).  The files are GPL version 2
(only); this unit is the only part of the project that comes from them.  Books 67.. are numbered in the OT
file after Malachi."""
import re, sys, os
inc = sys.argv[1]
def rd(f): return open(os.path.join(inc, f), encoding='utf-8').read()
def books_of(src, name):
    m = re.search(r'struct sbook %s\[\] = \{(.*?)\n\};' % name, src, re.S)
    return [(b.group(1), b.group(3), b.group(2), int(b.group(4)))      # name, osis, abbrev, chaps
            for b in re.finditer(r'\{"([^"]+)", "([^"]*)", "([^"]*)", (\d+)\}', m.group(1)) if b.group(4) != '0']
def vm_of(src, name):
    m = re.search(r'int %s\[\] = \{(.*?)\n\};' % name, src, re.S)
    return [int(x) for x in re.findall(r'\d+', re.sub(r'//[^\n]*', '', m.group(1)))]
kjv, kjva, nrsv, nrsva = rd('canon.h'), rd('canon_kjva.h'), rd('canon_nrsv.h'), rd('canon_nrsva.h')
ot = books_of(kjv, 'otbooks'); nt = books_of(kjv, 'ntbooks')
canon = ot + nt
assert len(ot) == 39 and len(nt) == 27
ncanon = sum(b[3] for b in canon)
vm_kjv, vm_nrsv = vm_of(kjv, 'vm'), vm_of(nrsv, 'vm_nrsv')
assert len(vm_kjv) == len(vm_nrsv) == ncanon == 1189
def apoc(src, otname, vmname, base_vm):
    o = books_of(src, otname)
    assert [b[0] for b in o[:39]] == [b[0] for b in ot]
    extra = o[39:]
    v = vm_of(src, vmname)
    nap = sum(b[3] for b in extra)
    assert len(v) == ncanon + nap
    otc = sum(b[3] for b in ot)
    assert v[:otc] == base_vm[:otc] and v[otc + nap:] == base_vm[otc:], "canon part differs"
    return extra, v[otc:otc + nap]
ap_kjva, apvm_kjva = apoc(kjva, 'otbooks_kjva', 'vm_kjva', vm_kjv)
ap_nrsva, apvm_nrsva = apoc(nrsva, 'otbooks_nrsva', 'vm_nrsva', vm_nrsv)
def lit(s): return "'" + s.replace("'", "''") + "'"
def recs(bs): return ",\n".join("    (Name: %s; OSIS: %s; Abbrev: %s; Chaps: %d)" % (lit(n), lit(o), lit(a), c) for n, o, a, c in bs)
def arr(name, v, per=16):
    return ("  %s: Array[0..%d] Of Byte = (\n" % (name, len(v) - 1)) + ",\n".join("    " + ", ".join(map(str, v[i:i+per])) for i in range(0, len(v), per)) + ");\n"
o = []
o.append("Unit MKBibVrA;       {The Apocrypha of the KJVA and NRSVA versifications - GENERATED by tools/genvra.py from Sword canon*.h}\n")
o.append("{ These tables come from the CrossWire Bible Society's Sword canon*.h files, which are under the GNU General Public\n  License version 2 (only): a Sword module is indexed by Sword's own counts, so they are copied as they are.  This is\n  the one unit of the project that is derived from Sword.  See the License section of README.md. }\n")
o.append("""{$I MKBib.Def}

Interface

Const
  NApocKJVA = %d;
  NApocNRSVA = %d;
  MaxApocBooks = %d;

Type
  ApocBookRec = Record Name, OSIS, Abbrev: String[24]; Chaps: Byte; End;

Const
  ApocKJVA: Array[1..%d] Of ApocBookRec = (
%s);
  ApocNRSVA: Array[1..%d] Of ApocBookRec = (
%s);
""" % (len(ap_kjva), len(ap_nrsva), max(len(ap_kjva), len(ap_nrsva)), len(ap_kjva), recs(ap_kjva), len(ap_nrsva), recs(ap_nrsva)))
o.append("Const\n" + arr("ApocVMKJVA", apvm_kjva) + arr("ApocVMNRSVA", apvm_nrsva))
o.append("\nImplementation\n\nEnd.\n")
open(sys.argv[2], 'w').write("\n".join(o))
